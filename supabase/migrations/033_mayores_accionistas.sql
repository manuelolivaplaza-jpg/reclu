-- ============================================================
-- Migracion 033 (F33): 12 mayores accionistas CMF (cl_top_shareholders).
--
-- La CMF publica, en la pestania 5 de la ficha de cada emisor, sus 12
-- mayores accionistas por periodo trimestral (03, 06, 09 y 12): nombre,
-- acciones suscritas, acciones pagadas y % de propiedad.
--
-- La llena `scrapers/stages/cmf_accionistas.py` desde
-- `institucional/mercados/entidad.php?...&pestania=5`. El RUT del emisor
-- se cruza con el mapa verificado de F15 (`rut_nemotecnico.json`) para
-- obtener el nemotecnico.
--
-- Datos: informacion publica y oficial de la CMF. Si la CMF publica una
-- persona natural como accionista, se guarda tal cual la fuente, sin
-- cruzarla con otras bases ni inferir datos adicionales (Leyes 19.628 y
-- 21.719). Dato informativo: no ejecuta ordenes ni es recomendacion.
--
-- Idempotente: create table/index if not exists, policy con drop + create.
-- Reejecutar dos veces seguidas no rompe.
-- ============================================================

-- ----------------------------------------------------------------------------
-- Tabla de mayores accionistas por emisor y periodo
-- ----------------------------------------------------------------------------
create table if not exists public.cl_top_shareholders (
  id bigint generated by default as identity primary key,
  rut_emisor text not null,
  nemo text,
  razon_social text,
  periodo text not null,
  ranking smallint
    check (ranking is null or (ranking >= 1 and ranking <= 12)),
  accionista text not null,
  porcentaje_propiedad numeric(9, 4)
    check (porcentaje_propiedad is null
           or (porcentaje_propiedad >= 0 and porcentaje_propiedad <= 100)),
  acciones_suscritas bigint
    check (acciones_suscritas is null or acciones_suscritas >= 0),
  acciones_pagadas bigint
    check (acciones_pagadas is null or acciones_pagadas >= 0),
  fuente text not null default 'cmf',
  source_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint cl_top_shareholders_unique
    unique (rut_emisor, periodo, accionista),
  constraint cl_top_shareholders_periodo_formato
    check (periodo ~ '^[0-9]{4}-(03|06|09|12)$')
);

comment on table public.cl_top_shareholders is
  '12 mayores accionistas de emisores chilenos (CMF, pestania 5). Una fila por emisor + periodo + accionista.';

comment on column public.cl_top_shareholders.rut_emisor is
  'RUT del emisor sin puntos ni digito verificador (clave del mapa F15).';

comment on column public.cl_top_shareholders.periodo is
  'Periodo informado por la CMF en formato YYYY-MM (mes 03, 06, 09 o 12).';

comment on column public.cl_top_shareholders.porcentaje_propiedad is
  '% de propiedad publicado por la CMF. 0 significa no calculado o no significativo.';

create index if not exists idx_cl_top_shareholders_emisor
  on public.cl_top_shareholders (rut_emisor, periodo desc);

create index if not exists idx_cl_top_shareholders_nemo
  on public.cl_top_shareholders (nemo, periodo desc);

create index if not exists idx_cl_top_shareholders_periodo
  on public.cl_top_shareholders (periodo desc, porcentaje_propiedad desc);

alter table public.cl_top_shareholders enable row level security;

drop policy if exists "cl_top_shareholders public read" on public.cl_top_shareholders;
create policy "cl_top_shareholders public read"
  on public.cl_top_shareholders
  for select
  using (true);
-- Sin policies de insert/update/delete: solo el service role escribe.

grant select on table public.cl_top_shareholders to anon, authenticated;
