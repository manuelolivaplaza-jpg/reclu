-- ============================================================
-- Migración 035 (F35): flujos diarios de ETFs ("dónde entra la plata")
--
-- Flujo diario estimado = Δ acciones en circulación × NAV por acción.
-- Las acciones en circulación salen de la cabecera del CSV oficial de
-- iShares ('Shares Outstanding'), el mismo archivo que alimenta los
-- holdings en scrapers/etfs.py. El NAV por acción se estima con el
-- patrimonio del fondo dividido por las acciones en circulación.
--
-- Fuente: iShares (BlackRock), archivos públicos y sin login.
-- La etapa que escribe es scrapers/stages/etf_flows.py.
--
-- Legal: datos de mercado públicos, sin datos personales (Leyes 19.628 y
-- 21.719). Dato informativo: no ejecuta órdenes ni es recomendación de
-- inversión (Ley Fintec). No se usan datos de funcionarios de EE.UU.
--
-- Idempotente: create table/index if not exists, trigger con drop + create
-- y policies con drop + create. Reejecutar dos veces no rompe.
-- ============================================================

-- ----------------------------------------------------------------------------
-- 1. Flujos por ETF y fecha
-- ----------------------------------------------------------------------------
create table if not exists public.etf_flows (
  id bigint generated by default as identity primary key,
  symbol text not null,
  fecha date not null,
  acciones numeric(20, 4) not null
    check (acciones >= 0),
  nav numeric(18, 6)
    check (nav is null or nav > 0),
  flujo_usd numeric(20, 2) not null default 0,
  fuente text not null default 'ishares',
  source_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint etf_flows_unique
    unique (symbol, fecha)
);

comment on table public.etf_flows is
  'Flujo diario de los ETFs: Δ acciones en circulación × NAV por acción. Estimación a partir de la cabecera del CSV oficial de iShares. Dato informativo, no es recomendación de inversión.';

comment on column public.etf_flows.acciones is
  'Acciones en circulación informadas por el emisor en la cabecera del CSV (Shares Outstanding).';

comment on column public.etf_flows.nav is
  'Valor liquidativo por acción estimado (patrimonio del fondo / acciones en circulación).';

comment on column public.etf_flows.flujo_usd is
  'Flujo del día en USD: (acciones de hoy - acciones de la lectura anterior) × NAV. 0 si no hay lectura anterior o no hay NAV.';

create index if not exists idx_etf_flows_symbol_fecha
  on public.etf_flows (symbol, fecha desc);

create index if not exists idx_etf_flows_fecha
  on public.etf_flows (fecha desc);

-- ----------------------------------------------------------------------------
-- 2. RLS: lectura publica, escritura solo service role
-- ----------------------------------------------------------------------------
alter table public.etf_flows enable row level security;

drop policy if exists "etf_flows public read" on public.etf_flows;
create policy "etf_flows public read"
  on public.etf_flows
  for select
  using (true);
-- Sin policies de insert/update/delete: solo el service role escribe.

grant select on table public.etf_flows to anon, authenticated;

-- ----------------------------------------------------------------------------
-- 3. Trigger de updated_at (reutiliza la funcion de schema.sql)
-- ----------------------------------------------------------------------------
drop trigger if exists set_etf_flows_updated_at
  on public.etf_flows;
create trigger set_etf_flows_updated_at
  before update on public.etf_flows
  for each row execute function public.set_updated_at();
