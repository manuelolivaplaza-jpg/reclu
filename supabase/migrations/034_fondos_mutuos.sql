-- ============================================================
-- Migracion 034 (F34): carteras de fondos mutuos chilenos (CMF).
--
-- Fuente: CMF, Circular 1333. La etapa `scrapers/stages/cmf_fondos.py`
-- descarga el archivo de cartera nacional del ultimo mes cerrado y elige
-- los 5 fondos de acciones nacionales con mayor cartera nacional
-- informada (`ffm_cartera.php` -> `ffm_download.php`, cartera NACI).
--
-- Datos: informacion publica y oficial de la CMF. Sin datos personales
-- (Leyes 19.628 y 21.719). Dato informativo: no ejecuta ordenes ni es
-- recomendacion de inversion (Ley Fintec).
--
-- Idempotente: create table/index if not exists, policies con
-- drop + create, vista con drop + create y portafolio con
-- `on conflict (slug) do update`. Reejecutar dos veces no rompe.
-- ============================================================

-- ----------------------------------------------------------------------------
-- 1. Ranking de fondos por periodo
-- ----------------------------------------------------------------------------
create table if not exists public.cl_mutual_funds (
  id bigint generated by default as identity primary key,
  run text not null,
  nombre text not null,
  periodo text not null,
  cartera_nacional_clp bigint not null default 0
    check (cartera_nacional_clp >= 0),
  posiciones integer not null default 0
    check (posiciones >= 0),
  fuente text not null default 'cmf',
  source_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint cl_mutual_funds_unique
    unique (run, periodo),
  constraint cl_mutual_funds_periodo_formato
    check (periodo ~ '^[0-9]{4}-(0[1-9]|1[0-2])$')
);

comment on table public.cl_mutual_funds is
  'Fondos mutuos chilenos por periodo (CMF, Circular 1333). cartera_nacional_clp es la suma de valorizaciones de la cartera nacional informada, usada para el ranking.';

comment on column public.cl_mutual_funds.run is
  'RUN del fondo segun la CMF (sin digito verificador).';

comment on column public.cl_mutual_funds.cartera_nacional_clp is
  'Valor de la cartera nacional informada, en pesos. Aproximacion al patrimonio: la CMF publica el patrimonio exacto en otro archivo.';

create index if not exists idx_cl_mutual_funds_periodo
  on public.cl_mutual_funds (periodo desc, cartera_nacional_clp desc);

create index if not exists idx_cl_mutual_funds_run
  on public.cl_mutual_funds (run, periodo desc);

-- ----------------------------------------------------------------------------
-- 2. Posiciones por fondo y periodo
-- ----------------------------------------------------------------------------
create table if not exists public.cl_mutual_fund_holdings (
  id bigint generated by default as identity primary key,
  fund_run text not null,
  fund_name text not null default '',
  periodo text not null,
  symbol text not null,
  name text not null default '',
  tipo_instrumento text not null default 'ACC',
  weight numeric(6, 2) not null
    check (weight >= 0 and weight <= 100),
  previous_weight numeric(6, 2)
    check (previous_weight is null
           or (previous_weight >= 0 and previous_weight <= 100)),
  valorizacion_miles bigint not null default 0
    check (valorizacion_miles >= 0),
  currency text not null default 'CLP'
    check (currency in ('USD', 'CLP', 'EUR')),
  source_url text,
  created_at timestamptz not null default now(),
  constraint cl_mutual_fund_holdings_unique
    unique (fund_run, periodo, symbol),
  constraint cl_mutual_fund_holdings_periodo_formato
    check (periodo ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  constraint cl_mutual_fund_holdings_fund_fk
    foreign key (fund_run, periodo)
    references public.cl_mutual_funds (run, periodo)
    on delete cascade
);

comment on table public.cl_mutual_fund_holdings is
  'Posiciones de los fondos mutuos chilenos seleccionados (CMF). Una fila por fondo + periodo + nemotecnico.';

comment on column public.cl_mutual_fund_holdings.previous_weight is
  'Peso del mes anterior. 0 marca una posicion nueva; null = sin comparacion mensual.';

comment on column public.cl_mutual_fund_holdings.valorizacion_miles is
  'Valorizacion al cierre informada por la CMF, en miles de pesos.';

create index if not exists idx_cl_mutual_fund_holdings_periodo
  on public.cl_mutual_fund_holdings (periodo desc, weight desc);

create index if not exists idx_cl_mutual_fund_holdings_symbol
  on public.cl_mutual_fund_holdings (symbol, periodo desc);

create index if not exists idx_cl_mutual_fund_holdings_fund
  on public.cl_mutual_fund_holdings (fund_run, periodo desc);

-- ----------------------------------------------------------------------------
-- 3. Vista de ranking (la consulta que usa la UI)
-- ----------------------------------------------------------------------------
drop view if exists public.cl_mutual_funds_ranking;
create view public.cl_mutual_funds_ranking
  with (security_invoker = true)
as
select
  periodo,
  rank() over (
    partition by periodo
    order by cartera_nacional_clp desc
  ) as ranking,
  run,
  nombre,
  cartera_nacional_clp,
  posiciones,
  fuente,
  source_url
from public.cl_mutual_funds;

comment on view public.cl_mutual_funds_ranking is
  'Ranking de fondos mutuos por cartera nacional informada (CMF) y periodo.';

-- ----------------------------------------------------------------------------
-- 4. RLS: lectura publica, escritura solo service role
-- ----------------------------------------------------------------------------
alter table public.cl_mutual_funds enable row level security;
alter table public.cl_mutual_fund_holdings enable row level security;

drop policy if exists "cl_mutual_funds public read" on public.cl_mutual_funds;
create policy "cl_mutual_funds public read"
  on public.cl_mutual_funds
  for select
  using (true);

drop policy if exists "cl_mutual_fund_holdings public read"
  on public.cl_mutual_fund_holdings;
create policy "cl_mutual_fund_holdings public read"
  on public.cl_mutual_fund_holdings
  for select
  using (true);
-- Sin policies de insert/update/delete: solo el service role escribe.

grant select on table public.cl_mutual_funds to anon, authenticated;
grant select on table public.cl_mutual_fund_holdings to anon, authenticated;
grant select on table public.cl_mutual_funds_ranking to anon, authenticated;

-- ----------------------------------------------------------------------------
-- 5. Trigger de updated_at (reutiliza la funcion de schema.sql)
-- ----------------------------------------------------------------------------
drop trigger if exists set_cl_mutual_funds_updated_at
  on public.cl_mutual_funds;
create trigger set_cl_mutual_funds_updated_at
  before update on public.cl_mutual_funds
  for each row execute function public.set_updated_at();

